# Bitmap matrix per glyph: 7 rows x 5 cols, 1 = ink.
GLYPHS = {
    ch: [[1 if c == "#" else 0 for c in row] for row in rows]
    for ch, rows in _GLYPHS_RAW.items()
}

CHARSET = "".join(GLYPHS.keys())


def render_char(ch, scale=1):
    """Return (width, height, rows-of-bits) for one character."""
    g = GLYPHS.get(ch, GLYPHS[" "])
    h = 7 * scale
    w = 5 * scale
    rows = []
    for base_row in g:
        line = []
        for bit in base_row:
            line.extend([bit] * scale)
        for _ in range(scale):
            rows.append(list(line))
    return w, h, rows
